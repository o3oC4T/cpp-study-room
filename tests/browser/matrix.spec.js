import {test, expect} from '@playwright/test';

test('row-by-row allocation and deletion leave the outer pointer array until the final step', async ({page}) => {
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/#/learn/dynamic-nested');
  const walkthrough=page.getByRole('group',{name:'2차원 배열: 한 줄씩 따라가기',exact:true});
  await expect(walkthrough).toBeVisible();
  const section=page.locator('.lesson-section').filter({has:walkthrough});
  await section.getByText('실행 결과 확인',{exact:true}).click();
  await expect(section.locator('.example-output pre')).toHaveText('(출력 없음)');
  const next=walkthrough.getByRole('button',{name:'다음 단계 →',exact:true});
  const prev=walkthrough.getByRole('button',{name:'← 이전 단계',exact:true});
  const row0=walkthrough.locator('.matrix-row').nth(0),row1=walkthrough.locator('.matrix-row').nth(1);
  const outer=walkthrough.locator('.matrix-pointers');
  await expect(prev).toBeDisabled();
  await expect(outer).toHaveAttribute('data-state','absent');
  await expect(walkthrough.locator('.matrix-summary')).toContainText('남은 동적 배열 0개');
  await next.click();
  await expect(outer).toHaveAttribute('data-state','allocated');
  await expect(outer.locator('.matrix-pointer-slot')).toHaveCount(2);
  await expect(outer).toContainText('미초기화');
  await expect(row0).toHaveAttribute('data-state','absent');
  await expect(row1).toHaveAttribute('data-state','absent');
  await expect(walkthrough.locator('.matrix-value')).toHaveCount(0);
  await next.click();
  await expect(walkthrough.locator('.walkthrough-step-label')).toHaveText('첫 번째 반복문 · i = 0');
  await expect(row0.locator('.matrix-value')).toHaveCount(3);
  await expect(row1).toHaveAttribute('data-state','absent');
  await next.click();
  await expect(walkthrough.locator('.walkthrough-step-label')).toHaveText('첫 번째 반복문 · i = 1');
  await expect(row1.locator('.matrix-value')).toHaveCount(3);
  await expect(walkthrough.locator('.matrix-summary')).toContainText('남은 동적 배열 3개');
  // The existing structure walkthrough has its own position and controls.
  await page.locator('#memory-next').click();
  await expect(page.locator('#memory-position')).toHaveText('2 / 5');
  await next.click();
  await expect(walkthrough.locator('.walkthrough-step-label')).toHaveText('두 번째 반복문 · i = 0');
  await expect(row0).toHaveAttribute('data-state','released');
  await expect(row1).toHaveAttribute('data-state','allocated');
  await expect(outer).toHaveAttribute('data-state','allocated');
  await expect(outer).toContainText('해제된 0행 (사용 불가)');
  await expect(walkthrough.locator('.matrix-summary')).toContainText('남은 동적 배열 2개');
  await next.click();
  await expect(row1).toHaveAttribute('data-state','released');
  await expect(outer).toHaveAttribute('data-state','allocated');
  await expect(walkthrough.locator('.matrix-summary')).toContainText('남은 동적 배열 1개');
  await next.click();
  await expect(outer).toHaveAttribute('data-state','released');
  await expect(walkthrough.locator('.matrix-summary')).toContainText('남은 동적 배열 0개');
  await expect(walkthrough.locator('.memory-code')).toHaveText('delete[] matrix;');
  await expect(walkthrough.locator('.memory-note')).toContainText('nullptr로 바뀌지는 않으며');
  await expect(next).toBeDisabled();
  await expect(walkthrough.locator('[data-position]')).toHaveText('7 / 7');
  await expect(page.locator('#memory-position')).toHaveText('2 / 5');
  await prev.click();
  await expect(outer).toHaveAttribute('data-state','allocated');
  await expect(next).toBeEnabled();
  await page.setViewportSize({width:1280,height:900});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('matrix code blanks give per-line feedback and retain drafts without losing existing lesson progress',async({page})=>{
 await page.goto('/');
 await page.evaluate(()=>localStorage.setItem('cpp-room:lesson:guest:dynamic-nested',JSON.stringify({answers:{0:1,1:1},blank:true,complete:true})));
 await page.goto('/#/learn/dynamic-nested');
 const form=page.getByRole('form',{name:'2차원 배열 코드 채우기',exact:true});
 const inputs=form.locator('input');
 await expect(inputs).toHaveCount(4);
 await form.getByText('힌트 보기',{exact:true}).nth(0).click();
 await expect(form.locator('details').first()).toContainText('int**');
 for(const [i,answer] of ['int** matrix = new int[rows];','matrix[i] = new int[rows];','delete matrix[i];','delete[] matrix[i];'].entries())await inputs.nth(i).fill(answer);
 await form.getByRole('button',{name:'답 확인',exact:true}).click();
 await expect(form.locator('[data-summary]')).toContainText('4줄 중 0줄 정답');
 await expect(form.locator('[aria-invalid="true"]')).toHaveCount(4);
 await expect(form.locator('[data-feedback="2"]')).toContainText('delete[]');
 await expect(page.locator('#blank-feedback')).toContainText('이전에 통과');
 const correct=['int **matrix = new int * [rows];','*(matrix + i) = new int[cols];','delete [ ] *(matrix+i);','delete[] matrix;'];
 for(const [i,answer] of correct.entries())await inputs.nth(i).fill(answer);
 await form.getByRole('button',{name:'답 확인',exact:true}).click();
 await expect(form.locator('[data-summary]')).toContainText('4줄 모두 맞았어요');
 await page.locator('#matrix-walkthrough [data-next]').click();
 await expect(inputs.nth(0)).toHaveValue(correct[0]);
 await page.reload();
 for(const [i,answer] of correct.entries())await expect(inputs.nth(i)).toHaveValue(answer);
 await expect(form.locator('[data-summary]')).toContainText('4줄 모두 맞았어요');
 await expect(page.locator('#complete-lesson')).toHaveText('학습 완료 ✓');
 await inputs.nth(0).fill('int**matrix=newint*[rows];');
 await form.getByRole('button',{name:'답 확인',exact:true}).click();
 await expect(form.locator('[data-summary]')).toContainText('4줄 중 3줄 정답');
 await expect(inputs.nth(0)).toHaveAttribute('aria-invalid','true');
 await page.reload();
 await expect(inputs.nth(0)).toHaveValue('int**matrix=newint*[rows];');
 await expect(form.locator('[data-summary]')).toContainText('4줄 중 3줄 정답');
 await page.setViewportSize({width:1280,height:900});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
